#!/usr/bin/env python3
"""Prepare a deterministic, metadata-only PushT query-coverage manifest.

The manifest deliberately contains references rather than copied trajectory
data.  This CPU preparation step reads the small ``seq_lengths.pkl`` index and
checks the selected observation filenames.  It does not load a model, decode a
video, read trajectory tensors, download, install, compile, hash, or copy
dataset files.

The default contract is:

* 32 train episodes x 4 contexts = 128 train contexts;
* 8 validation episodes x 1 context = 8 held-out contexts;
* horizon 5 and frame skip 5;
* held-out contexts come from ``val`` and are split-isolated from ``train``.

The later GPU runner can use the recorded ``goal_frame_index`` as the terminal
goal frame and use the fixed query seeds to sample logged/CEM-like action
prefixes.  No action values are generated by this preparation step.
"""

from __future__ import annotations

import argparse
import json
import os
import pickle
import random
from pathlib import Path
from typing import Any, Iterable


DEFAULT_HORIZON = 5
DEFAULT_FRAME_SKIP = 5
DEFAULT_TRAIN_EPISODES = 32
DEFAULT_TRAIN_CONTEXTS_PER_EPISODE = 4
DEFAULT_HELDOUT_EPISODES = 8
DEFAULT_HELDOUT_CONTEXTS_PER_EPISODE = 1
DEFAULT_EPISODE_SELECTION_SEED = 20260920
DEFAULT_TRAIN_QUERY_SEED = 20260922
DEFAULT_HELDOUT_QUERY_SEEDS = (20264922, 20264923)
DEFAULT_TIMING_QUERY_SEED = 20270922

SEQUENCE_LENGTHS_FILE = "seq_lengths.pkl"
OBSERVATIONS_DIR = "obses"


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--horizon", type=int, default=DEFAULT_HORIZON)
    parser.add_argument("--frame-skip", type=int, default=DEFAULT_FRAME_SKIP)
    parser.add_argument("--train-episodes", type=int, default=DEFAULT_TRAIN_EPISODES)
    parser.add_argument(
        "--train-contexts-per-episode",
        type=int,
        default=DEFAULT_TRAIN_CONTEXTS_PER_EPISODE,
    )
    parser.add_argument("--heldout-episodes", type=int, default=DEFAULT_HELDOUT_EPISODES)
    parser.add_argument(
        "--heldout-contexts-per-episode",
        type=int,
        default=DEFAULT_HELDOUT_CONTEXTS_PER_EPISODE,
    )
    parser.add_argument(
        "--episode-selection-seed",
        type=int,
        default=DEFAULT_EPISODE_SELECTION_SEED,
    )
    parser.add_argument("--train-query-seed", type=int, default=DEFAULT_TRAIN_QUERY_SEED)
    parser.add_argument(
        "--heldout-query-seeds",
        type=int,
        nargs=2,
        default=list(DEFAULT_HELDOUT_QUERY_SEEDS),
    )
    parser.add_argument("--timing-query-seed", type=int, default=DEFAULT_TIMING_QUERY_SEED)
    return parser.parse_args()


def _require_compute_node() -> None:
    """Refuse local/login-node execution before inspecting staged data."""

    if not os.environ.get("PBS_JOBID"):
        raise RuntimeError(
            "PBS_JOBID is required; refusing staged-data inspection outside a PBS allocation"
        )
    nodefile = os.environ.get("PBS_NODEFILE")
    if not nodefile:
        raise RuntimeError(
            "PBS_NODEFILE is required; refusing staged-data inspection without a CPU allocation"
        )
    if not Path(nodefile).is_file():
        raise RuntimeError(f"PBS_NODEFILE is not a file: {nodefile}")
    host = os.uname().nodename.lower() if hasattr(os, "uname") else "unknown"
    if any(token in host for token in ("login", "head", "submit")):
        raise RuntimeError(f"refusing probable login/head/submit host: {host}")


def _require_at_least(name: str, value: int, minimum: int) -> None:
    if value < minimum:
        raise ValueError(f"{name} must be >= {minimum}, got {value}")


def _read_sequence_lengths(path: Path) -> list[int]:
    """Read only the small official episode-length index."""

    with path.open("rb") as handle:
        value = pickle.load(handle)

    if isinstance(value, dict):
        for key in ("seq_lengths", "lengths", "episode_lengths"):
            if key in value:
                value = value[key]
                break
        else:
            indexed = [(key, item) for key, item in value.items() if isinstance(key, int)]
            if len(indexed) != len(value):
                raise ValueError(f"unsupported sequence-length mapping in {path}")
            value = [item for _, item in sorted(indexed)]

    if hasattr(value, "tolist") and not isinstance(value, (list, tuple)):
        value = value.tolist()
    if not isinstance(value, (list, tuple)):
        raise ValueError(f"{path} must contain a list/tuple of episode lengths")

    lengths: list[int] = []
    for episode_id, raw_length in enumerate(value):
        try:
            length = int(raw_length)
        except (TypeError, ValueError) as exc:
            raise ValueError(
                f"invalid episode length at index {episode_id}: {raw_length!r}"
            ) from exc
        if length < 1:
            raise ValueError(f"episode {episode_id} has non-positive length {length}")
        lengths.append(length)
    if not lengths:
        raise ValueError(f"{path} contains no episode lengths")
    return lengths


def _inspect_split(data_root: Path, split: str) -> dict[str, Any]:
    split_root = data_root / split
    lengths_path = split_root / SEQUENCE_LENGTHS_FILE
    observations_root = split_root / OBSERVATIONS_DIR
    if not split_root.is_dir():
        raise FileNotFoundError(f"missing staged split directory: {split_root}")
    if not lengths_path.is_file():
        raise FileNotFoundError(f"missing staged episode-length index: {lengths_path}")
    if not observations_root.is_dir():
        raise FileNotFoundError(f"missing staged observation directory: {observations_root}")
    lengths = _read_sequence_lengths(lengths_path)
    return {
        "split": split,
        "relative_root": split,
        "episode_count": len(lengths),
        "sequence_length_min": min(lengths),
        "sequence_length_max": max(lengths),
        "sequence_lengths": lengths,
        "sequence_lengths_file": f"{split}/{SEQUENCE_LENGTHS_FILE}",
        "observations_dir": f"{split}/{OBSERVATIONS_DIR}",
    }


def _eligible_episode_ids(lengths: Iterable[int], horizon: int, frame_skip: int) -> list[int]:
    required_span = horizon * frame_skip
    # A zero-based terminal frame must be strictly smaller than episode length.
    return [episode_id for episode_id, length in enumerate(lengths) if length > required_span]


def _select_episode_ids(
    eligible: list[int], count: int, seed: int, split: str
) -> list[int]:
    if len(eligible) < count:
        raise ValueError(f"{split} has {len(eligible)} eligible episodes; need {count}")
    return sorted(random.Random(seed).sample(eligible, count))


def _select_starts(
    *, episode_id: int, episode_length: int, horizon: int, frame_skip: int,
    count: int, seed: int,
) -> list[int]:
    required_span = horizon * frame_skip
    max_start = episode_length - required_span - 1
    candidates = list(range(max_start + 1))
    if len(candidates) < count:
        raise ValueError(
            f"episode {episode_id} has {len(candidates)} valid starts; need {count}"
        )
    return sorted(random.Random(seed).sample(candidates, count))


def _make_contexts(
    *, split: str, lengths: list[int], episode_ids: list[int], horizon: int,
    frame_skip: int, contexts_per_episode: int, selection_seed: int,
    query_seeds: list[int],
) -> list[dict[str, Any]]:
    contexts: list[dict[str, Any]] = []
    for episode_id in episode_ids:
        episode_length = lengths[episode_id]
        starts = _select_starts(
            episode_id=episode_id,
            episode_length=episode_length,
            horizon=horizon,
            frame_skip=frame_skip,
            count=contexts_per_episode,
            seed=selection_seed + episode_id,
        )
        for context_index, start_step in enumerate(starts):
            target_steps = [
                start_step + (offset + 1) * frame_skip for offset in range(horizon)
            ]
            terminal_frame_index = target_steps[-1]
            context_ordinal = len(contexts)
            contexts.append(
                {
                    "context_id": (
                        f"{split}_episode_{episode_id:03d}_start_{start_step:06d}"
                    ),
                    "split": split,
                    "episode_id": episode_id,
                    "episode_key": f"{split}:episode_{episode_id:03d}",
                    "context_index_in_episode": context_index,
                    "context_ordinal": context_ordinal,
                    "episode_length": episode_length,
                    "observation_file": (
                        f"{split}/{OBSERVATIONS_DIR}/episode_{episode_id:03d}.mp4"
                    ),
                    "start": start_step,
                    "start_step": start_step,
                    "target_steps": target_steps,
                    "terminal_frame_index": terminal_frame_index,
                    "goal_frame_index": terminal_frame_index,
                    "context_selection_seed": selection_seed + episode_id,
                    "query_seeds": [seed + context_ordinal for seed in query_seeds],
                    "query_seed": query_seeds[0] + context_ordinal,
                }
            )
    return contexts


def _verify_observation_filenames(data_root: Path, contexts: Iterable[dict[str, Any]]) -> None:
    """Check directory entries only; never open or decode an observation file."""

    checked: set[str] = set()
    for context in contexts:
        relative = str(context["observation_file"])
        if relative in checked:
            continue
        checked.add(relative)
        path = data_root / relative
        if not path.is_file():
            raise FileNotFoundError(f"selected observation filename is missing: {path}")


def _build_manifest(args: argparse.Namespace) -> dict[str, Any]:
    _require_at_least("horizon", args.horizon, 1)
    _require_at_least("frame_skip", args.frame_skip, 1)
    _require_at_least("train_episodes", args.train_episodes, DEFAULT_TRAIN_EPISODES)
    _require_at_least(
        "train_contexts_per_episode",
        args.train_contexts_per_episode,
        DEFAULT_TRAIN_CONTEXTS_PER_EPISODE,
    )
    _require_at_least("heldout_episodes", args.heldout_episodes, DEFAULT_HELDOUT_EPISODES)
    _require_at_least(
        "heldout_contexts_per_episode",
        args.heldout_contexts_per_episode,
        DEFAULT_HELDOUT_CONTEXTS_PER_EPISODE,
    )
    if args.heldout_episodes != DEFAULT_HELDOUT_EPISODES:
        raise ValueError(
            f"heldout_episodes is fixed at {DEFAULT_HELDOUT_EPISODES}, got {args.heldout_episodes}"
        )
    if args.heldout_contexts_per_episode != DEFAULT_HELDOUT_CONTEXTS_PER_EPISODE:
        raise ValueError(
            "heldout_contexts_per_episode is fixed at 1 for the 8-context held-out split"
        )
    if len(args.heldout_query_seeds) != 2:
        raise ValueError("heldout_query_seeds must contain exactly two integers")

    data_root = args.data_root.resolve()
    if not data_root.is_dir():
        raise FileNotFoundError(f"data root is not a directory: {data_root}")
    train_layout = _inspect_split(data_root, "train")
    val_layout = _inspect_split(data_root, "val")

    train_eligible = _eligible_episode_ids(
        train_layout["sequence_lengths"], args.horizon, args.frame_skip
    )
    val_eligible = _eligible_episode_ids(
        val_layout["sequence_lengths"], args.horizon, args.frame_skip
    )
    train_ids = _select_episode_ids(
        train_eligible, args.train_episodes, args.episode_selection_seed, "train"
    )
    val_ids = _select_episode_ids(
        val_eligible, args.heldout_episodes, args.episode_selection_seed + 1, "val"
    )

    train_contexts = _make_contexts(
        split="train",
        lengths=train_layout["sequence_lengths"],
        episode_ids=train_ids,
        horizon=args.horizon,
        frame_skip=args.frame_skip,
        contexts_per_episode=args.train_contexts_per_episode,
        selection_seed=args.episode_selection_seed,
        query_seeds=[args.train_query_seed],
    )
    heldout_contexts = _make_contexts(
        split="val",
        lengths=val_layout["sequence_lengths"],
        episode_ids=val_ids,
        horizon=args.horizon,
        frame_skip=args.frame_skip,
        contexts_per_episode=args.heldout_contexts_per_episode,
        selection_seed=args.episode_selection_seed + 1,
        query_seeds=[int(seed) for seed in args.heldout_query_seeds],
    )
    _verify_observation_filenames(data_root, [*train_contexts, *heldout_contexts])

    train_keys = {context["episode_key"] for context in train_contexts}
    heldout_keys = {context["episode_key"] for context in heldout_contexts}
    if train_keys & heldout_keys:
        raise AssertionError("train and held-out episode keys overlap")

    return {
        "schema": "jepa-action-prefix-compiler.query-coverage-manifest",
        "schema_version": 1,
        "source": {
            "data_root": str(data_root),
            "layout_verified": True,
            "files_copied": False,
            "videos_decoded": False,
            "models_loaded": False,
            "hashes_computed": False,
            "metadata_file": SEQUENCE_LENGTHS_FILE,
            "observation_filenames_only": True,
        },
        "protocol": {
            "horizon": args.horizon,
            "frame_skip": args.frame_skip,
            "target_indexing": "zero-based observation-frame index",
            "goal_frame_semantics": "terminal target_steps frame; suitable for goal encoding",
            "action_query_distribution": "logged_plus_cem_mixture; sampled later by GPU runner",
            "action_query_mixture": {
                "logged_fraction": 0.5,
                "cem_initial_fraction": 0.25,
                "cem_intermediate_fraction": 0.25,
            },
            "episode_selection_seed": args.episode_selection_seed,
            "train_query_seed": args.train_query_seed,
            "heldout_query_seeds": [int(seed) for seed in args.heldout_query_seeds],
            "timing_query_seed": args.timing_query_seed,
            "train_episode_count": len(train_ids),
            "train_contexts_per_episode": args.train_contexts_per_episode,
            "train_context_count": len(train_contexts),
            "heldout_episode_count": len(val_ids),
            "heldout_contexts_per_episode": args.heldout_contexts_per_episode,
            "heldout_context_count": len(heldout_contexts),
            "episode_split_isolation": "train split versus val split; split-local episode IDs",
        },
        "files": {
            "sequence_lengths": "{split}/seq_lengths.pkl",
            "observations": "{split}/obses/episode_{episode_id:03d}.mp4",
        },
        "splits": {
            "train": {
                "source_split": "train",
                "episode_ids": train_ids,
                "contexts": train_contexts,
            },
            "heldout": {
                "source_split": "val",
                "episode_ids": val_ids,
                "contexts": heldout_contexts,
            },
        },
    }


def main() -> int:
    _require_compute_node()
    args = _parse_args()
    output = args.output.resolve()
    if output.exists():
        raise FileExistsError(f"refusing to overwrite existing manifest: {output}")
    manifest = _build_manifest(args)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("x", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=2, sort_keys=True)
        handle.write("\n")
    print(f"manifest={output}")
    print(f"train_episodes={manifest['protocol']['train_episode_count']}")
    print(f"train_contexts={manifest['protocol']['train_context_count']}")
    print(f"heldout_episodes={manifest['protocol']['heldout_episode_count']}")
    print(f"heldout_contexts={manifest['protocol']['heldout_context_count']}")
    print(f"horizon={manifest['protocol']['horizon']} frame_skip={manifest['protocol']['frame_skip']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
